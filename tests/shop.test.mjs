import { searchScore, searchRows } from "../js/shopsearch.js";
import * as S from "../js/shopdata.js";
let n = 0; const ok = (c, m) => { if (!c) { console.log("FAIL", m); process.exitCode = 1; } else n++; };
ok(searchScore("Longsword", "longsword") === 0, "exact");
ok(searchScore("Longsword", "lonsword") != null, "typo missing letter");
ok(searchScore("Longsword", "longsowrd") != null, "typo swap");
ok(searchScore("Chain Mail", "chian") != null, "typo word");
ok(searchScore("Potion of Healing", "heal potion") != null, "two words any order");
ok(searchScore("Dagger", "sword") === null, "no match");
ok(searchScore("Dagger", "ax") === null, "short no fuzz");
ok(searchRows([{ name: "Handaxe" }, { name: "Greataxe" }, { name: "Axe Beak" }], "axe")[0].name === "Axe Beak", "prefix first");
const c = { shop: null };
S.cartAdd(c, "Dagger"); S.cartAdd(c, "Dagger", 2); ok(S.cartQty(c, "Dagger") === 3, "qty adds");
S.cartLater(c, "Dagger"); ok(S.cartQty(c, "Dagger") === 0 && c.shop.later[0].qty === 3, "later");
S.laterBack(c, "Dagger"); ok(S.cartQty(c, "Dagger") === 3 && !c.shop.later.length, "back");
S.cartSet(c, "Dagger", 0); ok(S.cartCount(c) === 0, "remove");
ok(S.shopOf(c).lists.length === 1, "default list");
const id = S.listCreate(c, "Boss fight"); ok(S.listToggle(c, "Dagger", id) && S.listHas(c, "Dagger"), "list add");
ok(!S.listToggle(c, "Dagger", id) && !S.listHas(c, "Dagger"), "list remove");
S.listDelete(c, id); ok(c.shop.lists.length === 1, "delete list");
S.listDelete(c, c.shop.lists[0].id); ok(c.shop.lists.length === 1, "last list stays");
const bad = S.cleanShop({ cart: [{ name: 5 }, { name: "A", qty: -3 }, null], lists: [{ name: "x", items: ["a", "a", 3] }] });
ok(bad.cart.length === 1 && bad.cart[0].qty === 1 && bad.lists[0].items.length === 1, "clean");
const rows = [{ name: "B", gp: 5 }, { name: "A", gp: 1 }, { name: "C", gp: 9 }], ctx = { price: r => r.gp, weight: r => r.name === "A" ? null : r.gp };
ok(S.sortRows(rows, "price-asc", ctx)[0].name === "A" && S.sortRows(rows, "price-desc", ctx)[0].name === "C", "price sort");
ok(S.sortRows(rows, "weight-asc", ctx)[2].name === "A" && S.sortRows(rows, "weight-desc", ctx)[2].name === "A", "unknown weight last");
S.cartAdd(c, "B", 2); S.cartAdd(c, "Zed");
const sum = S.cartSummary(c, nm => rows.find(r => r.name === nm), { ...ctx, attune: r => r.name === "B" }, 500);
ok(sum.totalCp === 1000 && sum.gone[0] === "Zed" && sum.attune === 2 && sum.shortCp === 500 && sum.leftCp === -500, "summary");
console.log("shop: " + n + " checks passed");
